// Server HTTP Routing
const server = http.createServer((req, res) => {
  const url = new URL(req.url, `http://${req.headers.host}`);
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

  if (req.method === 'OPTIONS') {
    res.writeHead(204);
    res.end();
    return;
  }

  if (url.pathname === '/health' || url.pathname === '/ooda') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({
      server: "Omie Military Bridge Server",
      port: PORT,
      timestamp: new Date().toISOString(),
      ooda_boa: calculateBoaScore()
    }, null, 2));

  } else if (url.pathname === '/openapi') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(generateOpenApiSpec(), null, 2));

  } else if (url.pathname === '/types') {
    res.writeHead(200, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end(generateTsTypes());

  } else if (url.pathname === '/cross-map') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(generateCrossMap(), null, 2));

  } else if (url.pathname.startsWith('/api/v1/')) {
    let body = '';
    req.on('data', chunk => body += chunk);
    req.on('end', async () => {
      try {
        const creds = getOmieCredentials();
        const payload = JSON.parse(body || '{}');
        payload.app_key = creds.app_key;
        payload.app_secret = creds.app_secret;

        const targetUrl = `https://app.omie.com.br${url.pathname}`;
        const omieRes = await fetch(targetUrl, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(payload)
        });

        const omieData = await omieRes.json();
        res.writeHead(omieRes.status, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify(omieData, null, 2));
      } catch (err) {
        res.writeHead(500, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: err.message }));
      }
    });
    return;
  } else {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({
      message: "Omie ERP Sovereign Bridge Server (:6661)",
      endpoints: [
        "GET /health     -> Status OODA / BOA Score",
        "GET /openapi    -> Esquema OpenAPI 3.1",
        "GET /types      -> Tipagem TypeScript (.ts)",
        "GET /cross-map  -> AST Mating (API Schemas + UI DOM)",
        "GET /probe      -> Status do Probe de Integração"
      ]
    }, null, 2));
  }
});

server.listen(PORT, () => {
  console.log(`🚀 [BRIDGE OMIE :6661] Servidor militar rodando em http://localhost:${PORT}`);
});

