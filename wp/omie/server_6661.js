    backend_coverage: `${(backendRatio * 100).toFixed(1)}%`,
    frontend_depth_coverage: depthScore === 10.0 ? "100.0%" : "61.6%",
    dimensions_audited: 6,
    assets_extracted: hasAssets,
    styles_computed: hasStyles,
