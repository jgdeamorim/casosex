// Helper to read Omie credentials
function getOmieCredentials() {
  if (!fs.existsSync(ENV_PATH)) return null;
  const content = fs.readFileSync(ENV_PATH, 'utf-8');
  let app_key = '', app_secret = '';
  content.split('\n').forEach(line => {
    if (line.includes('App Key:')) app_key = line.split('App Key:')[1].trim();
    if (line.includes('App Secret:')) app_secret = line.split('App Secret:')[1].trim();
  });
  return { app_key, app_secret };
}

// Calculate OODA BOA Score based on 6-Dimension Multidimensional Depth Audit
